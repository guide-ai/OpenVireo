    會在選單中以帶底線的字元顯示。要做出選擇，按相應的快速鍵。或者，按下
    「Alt」鍵後，用方向鍵在選單項目之間移動，再按「Enter」鍵選擇。
 
    -控制項-
    你可以用「Tab」鍵和「Shift-Tab」鍵在任何表單上的各個控制項（按鈕、開
