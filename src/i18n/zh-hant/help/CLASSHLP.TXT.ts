以下控制項位於分類視窗的右側：

    放大（向上箭頭）：
        將顯示的光譜放大2倍，最大可達原始顯示的16倍。如果已標記某個特
        徵，放大時會盡量讓它位於放大後顯示區的中央。如果沒有標記譜線，顯
        示區中心的波長保持不變。

    縮小（向下箭頭）：
        將顯示的光譜縮小2倍，最小回到原始倍率（1X）。如果已標記某條譜
