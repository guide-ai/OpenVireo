取り値をどのように解釈して記録するかを指定するために使います。読み取りを
始める「開始」（Start）ボタンを押す前に、このスイッチが正しい位置にある
ことを必ず確かめてください。読み取りスイッチを「空」（Sky）にしたまま恒
星などの天体を読み取ると、現在の（おそらく正しい）空の読み取り値が、その
天体を含む無効な値に置き換わってしまいます。そうなった場合は、天体から離
