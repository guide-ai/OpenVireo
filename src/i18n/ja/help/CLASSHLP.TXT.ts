        注：スペクトルが強度トレースとして表示されている場合（ヘルプト
        ピック「表示の設定」を参照）、強度の測定値はカーソルの縦位置（Y
        座標）で決まります。表示が「写真」（Photo）モードの場合は、（横
        方向、つまりX座標の）カーソルの「真下」にある強度が表示されま
