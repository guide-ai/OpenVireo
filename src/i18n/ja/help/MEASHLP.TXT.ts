これらの線の位置を調整して、測定の精度を上げられます。矢印キーを押し続け
て、次に測定したい特徴へ線を動かすこともできます（下記参照）。

    -キーボード操作-
    テンキーの矢印キー（「2」「4」「6」「8」のキー）を、マウスの代わりに
