import type {ReactNode} from 'react';
import {activeBundle,t,type MessageArgs,type MessageKey} from '../i18n';
import type {TermSnapshot} from '../i18n/catalog';
import ENGLISH_TERMS from '../i18n/terms.en.json';

/** Front NEWCOMER NC7 [W] (plan analysis/front-plans/front-newcomer.md §2.7; user decision of 2026-11-24): sixteen technical terms
 * of the exercise guides show a one-line textbook definition. A term is marked only where the guide window (its why-line and its
 * steps' text) or the companion strip's Step details already say it: no guide string changes. Which words are marked comes from
 * a reviewed per-language snapshot (`src/i18n/terms.en.json`, `src/i18n/<dir>/terms.json`: catalog key → [term, matched text,
 * occurrence]), generated by src/help/glossary.test.ts from each language's patterns (src/help/glossaryPatterns.ts) and gated by
 * the English string of the same key; a word the snapshot does not name, or that the rendered text does not hold, stays plain.
 * The marks are host `<button class="term">` elements made by plain functions (no component per term: the seven windows render
 * closed on every load, tests/render-budget.spec.ts); one TermPopover (components/TermPopover.tsx) shows the definition. A
 * definition is textbook-neutral: it states no lab's result, no expected value and nothing about Object X's identity
 * (src/guideLead.test.ts checks every language). Nothing is stored. */

/** The sixteen terms, in the order a string is searched (a longer or more specific term before the words it contains). */
export const TERM_IDS=['reddening','colorIndex','distanceModulus','hrDiagram','zams','mainSequence','isochrone','metallicity','dispersionMeasure',
 'pulsar','caHK','absorptionLine','redshift','spectrum','photometer','magnitude'] as const;
export type TermId=typeof TERM_IDS[number];
export const isTermId=(id:string):id is TermId=>(TERM_IDS as readonly string[]).includes(id);

/** A term's definition, by literal key (so the i18n split and the catalog checks see every key). */
export function termDefinition(id:TermId):string{
 switch(id){
  case 'redshift':return t('term.redshift');
  case 'spectrum':return t('term.spectrum');
  case 'absorptionLine':return t('term.absorptionLine');
  case 'caHK':return t('term.caHK');
  case 'magnitude':return t('term.magnitude');
  case 'colorIndex':return t('term.colorIndex');
  case 'photometer':return t('term.photometer');
  case 'hrDiagram':return t('term.hrDiagram');
  case 'mainSequence':return t('term.mainSequence');
  case 'zams':return t('term.zams');
  case 'isochrone':return t('term.isochrone');
  case 'reddening':return t('term.reddening');
  case 'distanceModulus':return t('term.distanceModulus');
  case 'metallicity':return t('term.metallicity');
  case 'pulsar':return t('term.pulsar');
  case 'dispersionMeasure':return t('term.dispersionMeasure');
 }
}

/** One step's (or one why-line's) marking: a term is marked at its first occurrence in the step only (`seen`); `found` collects
 * the terms of a whole window, for its «Words used in this guide». */
export type TermScope=Readonly<{seen:Set<string>;found?:Set<string>}>;
export const termScope=(found?:Set<string>):TermScope=>({seen:new Set(),found});

let recording:Set<string>|null=null;
/** Test only (src/help/glossary.test.ts): the keys every gloss call names while `run` renders, which the snapshot covers. */
export function recordGlossKeys(run:()=>void):ReadonlySet<string>{
 const keys=new Set<string>(),before=recording;recording=keys;
 try{run();}finally{recording=before;}
 return keys;
}

/** The snapshot of this load's language: its bundle's own, or for a dev pseudo-locale the English one with each matched text
 * passed through the pseudo-locale's own transform (its marks and padding taken off); null when there is none. */
function snapshot():{matches:TermSnapshot;derive?:(text:string)=>string}|null{
 const bundle=activeBundle();
 if(!bundle)return {matches:ENGLISH_TERMS};
 if(bundle.terms)return {matches:bundle.terms};
 // Dev server and tests only: deriveOriginal belongs to the pseudo-locales (src/i18n/pseudo.ts, pseudoScripts.ts), which mark a
 // string ⟦...⟧ with · padding; the branch is dropped from the production build with them.
 if(import.meta.env.DEV&&bundle.deriveOriginal){
  const derive=bundle.deriveOriginal,unmark=(d:string)=>d.startsWith('⟦')&&d.endsWith('⟧')?d.slice(1,-1).replace(/·+$/u,''):d;
  return {matches:ENGLISH_TERMS,derive:text=>unmark(derive(text))};
 }
 return null;
}
/** The start of the `n`th occurrence (from 0) of `part` in `text`, or -1. */
function nth(text:string,part:string,n:number){let at=-1;for(let i=0;i<=n;i++){at=text.indexOf(part,at+1);if(at<0)return -1;}return at;}

/** `text` (the rendered string of `key`) with the snapshot's terms marked: strings and `<button type="button" class="term">`
 * elements. Each term is marked once per scope; a match that is missing or overlaps an earlier one is left plain. */
export function glossText(scope:TermScope,key:string,text:string):ReactNode{
 recording?.add(key);
 const snap=snapshot(),entries=snap?.matches[key];
 if(!entries?.length)return text;
 const marks:{start:number;end:number;id:TermId}[]=[];
 for(const [id,matched,n] of entries){
  if(typeof id!=='string'||!isTermId(id)||scope.seen.has(id))continue;
  const part=snap!.derive?snap!.derive(String(matched)):String(matched),start=part?nth(text,part,Number(n)||0):-1;
  if(start<0||marks.some(m=>start<m.end&&m.start<start+part.length))continue;
  marks.push({start,end:start+part.length,id});scope.seen.add(id);scope.found?.add(id);
 }
 if(!marks.length)return text;
 marks.sort((a,b)=>a.start-b.start);
 const out:ReactNode[]=[];let at=0;
 marks.forEach(m=>{
  if(m.start>at)out.push(text.slice(at,m.start));
  // Keyed by term and place, so a re-render that moves or replaces a term makes a new button (review N1). The definition is the
  // button's `aria-description` (review N3), so a screen reader gives it with the term, open or not.
  out.push(<button key={`${m.id}:${m.start}`} type="button" className="term" aria-expanded="false" aria-description={termDefinition(m.id)} data-term={m.id}>{text.slice(m.start,m.end)}</button>);
  at=m.end;
 });
 if(at<text.length)out.push(text.slice(at));
 return out;
}
/** A catalog string with its terms marked (`key` is a catalog key, also a template one: `classLab.step.${step}.help`). */
export const glossKey=<K extends MessageKey>(scope:TermScope,key:K,...args:MessageArgs<K>):ReactNode=>glossText(scope,key,t(key,...args));

/** «Words used in this guide»: a folded list, at the end of a window, of the terms marked in it with their definitions (in the
 * order of TERM_IDS). Call it after the window's other text, so `found` is complete; nothing when no term was marked. Printing
 * opens it with the window's other folded parts (help/printDetails.ts). */
const HR_TERMS:readonly TermId[]=['mainSequence','zams','isochrone'];
export function wordsUsed(id:string,found:ReadonlySet<string>):ReactNode{
 // Review N2: the main sequence, the ZAMS and an isochrone are defined through the HR diagram, which the guides name only as
 // controls; a window that marks one of them lists the HR diagram too.
 const ids=TERM_IDS.filter(term=>found.has(term)||term==='hrDiagram'&&HR_TERMS.some(t=>found.has(t)));
 if(!ids.length)return null;
 return <details className="lab-terms" id={id}><summary>{t('term.wordsHeading')}</summary><ul>{ids.map(term=><li key={term} data-term={term}>{termDefinition(term)}</li>)}</ul></details>;
}
