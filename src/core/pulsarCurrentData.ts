/**
 * The one current pulsar signal dataset shared by the receiver Record path and the Pulsar Analysis window (R-RX4).
 * Pure TypeScript: no React, DOM, clock, RNG or storage.
 *
 * Native model (docs/RADIO-RECEIVER-RECORD.md, CLEA_VEO.exe SHA-256 781bc970…c54c): one data object behind the global
 * 0x5bcca0 (alias 0x5b5be8) holds the header at +4, the row list at +0x80, the file-origin byte +0x96, the saved byte
 * +0x97, the full byte +0x98, the new-data byte +0x99 and the file-name text +0x9a. The PLR reader 0x56a260, the Record
 * arming clear 0x56a8e0, the Receive header 0x574766..0x574969, the timer append 0x56a92c and the analysis/Properties
 * windows all use that object.
 *
 * WEB-REC-OWNER: the App owns one PulsarCurrentData document for the page lifetime (never saved, restored or sent).
 * `generation` increases on every dataset change. A receiver capture holds an exclusive lease while it is armed,
 * receiving, finishing or committed (the capture is current while the Properties and Save question are still open); while
 * it is held no import may commit (WEB-REC-TXN). The lease ends with exactly one release (Save No/Cancel, the R-RX17 verified
 * finish Save, disarm, the main receiver close). 'committed' is a web transaction phase, not a native flag. WEB buffered commit: the descriptor
 * changes only at the arming erase, at the capture commit (end of Identify, or the main receiver close) and at an
 * import; natively the header is written at Receive start and rows are appended to the shared object on each tick.
 *
 * A memory capture is model-generated by the receiver simulation, not observed CLEA data. It has no bytes, file name,
 * lexemes or line ending; its samples are the raw binary64 receiver signals copied once (no serialize/reparse).
 */
import { formatFixed, plrProperties, PLR_RESERVED_NAME, type PlrProperties, type PlrReceiverIndex, type PlrRecording } from './pulsarRecording';

/** Literal 0x5719a4 (AnsiString), shown by THdrDisp FileNmEd when +0x97 is 0 (0x571931..0x57194b). */
export const PULSAR_DATA_NOT_WRITTEN = 'Data Not Written to File';
/** ShortString 0x56b9bc compared with the header name at 0x56b7c9 and 0x56bf11 (same text as PLR_RESERVED_NAME). */
export const PULSAR_RESERVED_DATA_NAME = PLR_RESERVED_NAME;

type Cells<T> = readonly [T, T, T];
/**
 * Header cells at +4 as the web knows them. null: a cell no ported path has written (genuinely unrecovered or
 * uninitialized web cell). Receive writes every cell except the frequency and gain of absent receivers, which keep
 * their previous known values (WEB-REC-HEADER).
 */
export type PulsarHeaderCells = Readonly<{
  name: string | null; aperture: number | null; highestIndex: PlrReceiverIndex | null;
  frequencies: Cells<number | null>; gains: Cells<number | null>; start: number | null; interval: number | null;
}>;
export const EMPTY_PULSAR_HEADER: PulsarHeaderCells = Object.freeze({
  name: null, aperture: null, highestIndex: null, frequencies: Object.freeze([null, null, null] as const), gains: Object.freeze([null, null, null] as const), start: null, interval: null,
});

/**
 * A finished or partial receiver capture held only in memory (+0x96 = 0; +0x97 = 0 when the capture is committed). The
 * R-RX15 verified copy is kept separately on the document (`written`) and read through pulsarWrittenCopy / pulsarCurrentSaved.
 */
export type PulsarMemoryRecording = Readonly<{
  origin: 'memory'; source: 'radio-receiver-model'; captureId: number;
  name: string; aperture: number; highestIndex: PlrReceiverIndex;
  /** Absent receivers keep the previous known cell, or null. Recorded receivers (≤ highestIndex) are always numbers. */
  frequencies: Cells<number | null>;
  /** Raw +0x53d × +0x40f products; no import zero replacement. */
  gains: Cells<number | null>;
  start: number; interval: number;
  rowCount: number;
  /** Row-major rows×3 raw binary64 receiver signals, in append order. */
  samples: Float64Array;
  /** +0x98: the append found the list at its bound. */
  full: boolean;
}>;
/** The header left after the arming clear 0x56a8e0: no rows, +0x96/+0x97/+0x98 = 0, header cells kept. */
export type PulsarClearedData = Readonly<{ origin: 'cleared'; header: PulsarHeaderCells }>;
export type PulsarData = PlrRecording | PulsarMemoryRecording;
export type PulsarCurrentValue = PulsarData | PulsarClearedData;
export const isMemoryData = (d: PulsarCurrentValue | null): d is PulsarMemoryRecording => d !== null && 'origin' in d && d.origin === 'memory';
export const isClearedData = (d: PulsarCurrentValue | null): d is PulsarClearedData => d !== null && 'origin' in d && d.origin === 'cleared';
export const isFileData = (d: PulsarCurrentValue | null): d is PlrRecording => d !== null && !('origin' in d);

export type PulsarCaptureLease = Readonly<{ id: number; phase: 'armed' | 'receiving' | 'finishing' | 'committed' }>;
/** What the analysis window reports so arming can refuse while it has a modal session or a pending read. */
export type PulsarAnalysisActivity = Readonly<{ modal: boolean; reading: boolean }>;
export type PulsarCurrentData = Readonly<{
  generation: number;
  data: PulsarCurrentValue | null;
  lease: PulsarCaptureLease | null;
  analysis: PulsarAnalysisActivity;
  /**
   * R-RX15 (docs/PULSAR-SAVE-VERIFIED.md): the last verified browser copy of this memory capture, or null/absent. Historical:
   * it says that a copy was read back equal at that time, not that the file is still there or unchanged. Only
   * recordPulsarWrittenCopy and, for the R-RX17 finish owner, recordPulsarFinishWrittenCopy create one; every dataset change
   * (bump) drops it. Read it through pulsarWrittenCopy.
   */
  written?: PulsarWrittenCopy | null;
  /**
   * R-RX16 (docs/RADIO-RECORD-SAVE.md, WEB-RX16-05): the one browser output attempt of the page, or null/absent. Taken by
   * the Pulsar Analysis Save or a Radio Save (arming, or R-RX17 finish) before its picker call and released by that owner, with that token,
   * only after its stream cleanup settled. Kept by every dataset change (bump) and by a receipt; it is not a native flag.
   */
  output?: PulsarOutputClaim | null;
}>;
export const INITIAL_PULSAR_CURRENT_DATA: PulsarCurrentData = Object.freeze({
  generation: 0, data: null, lease: null, analysis: Object.freeze({ modal: false, reading: false }), written: null, output: null,
});

export type PulsarDataRefusal = 'capture-lease' | 'superseded' | 'analysis-busy' | 'lease-mismatch';
export type PulsarDataStep = Readonly<{ doc: PulsarCurrentData; ok: true } | { doc: PulsarCurrentData; ok: false; reason: PulsarDataRefusal }>;
const ok = (doc: PulsarCurrentData): PulsarDataStep => Object.freeze({ doc: Object.freeze(doc), ok: true });
const refuse = (doc: PulsarCurrentData, reason: PulsarDataRefusal): PulsarDataStep => Object.freeze({ doc, ok: false, reason });

// ---------------------------------------------------------------- accessors
/** Rows in the +0x80 list (0 for no data or a cleared header). */
export const pulsarDataRows = (d: PulsarCurrentValue | null) => d === null || isClearedData(d) ? 0 : d.rowCount;
/**
 * +0x97 of the value alone: set by a successful read (0x56a49d..0x56a4be); 0 after a clear and a Receive header write.
 * @deprecated R-RX15: a memory capture can also have a verified written copy, which only the document knows. Use
 * pulsarCurrentSaved(doc). Kept for callers that hold only a value (it answers as before R-RX15).
 */
export const pulsarDataSaved = (d: PulsarCurrentValue | null) => isFileData(d);
/** The header cells of the current value (the Receive seed, WEB-REC-HEADER). File gains are the effective (zero → 1) values. */
export function pulsarHeaderCells(d: PulsarCurrentValue | null): PulsarHeaderCells {
  if (d === null) return EMPTY_PULSAR_HEADER;
  if (isClearedData(d)) return d.header;
  if (isMemoryData(d)) return Object.freeze({ name: d.name, aperture: d.aperture, highestIndex: d.highestIndex, frequencies: d.frequencies, gains: d.gains, start: d.start, interval: d.interval });
  return Object.freeze({
    name: d.name, aperture: d.aperture.value, highestIndex: d.highestIndex.value,
    frequencies: Object.freeze([d.frequencies[0].value, d.frequencies[1].value, d.frequencies[2].value] as const),
    gains: Object.freeze([d.gains[0].effective, d.gains[1].effective, d.gains[2].effective] as const), start: d.start.value, interval: d.interval.value,
  });
}
export const pulsarDataName = (d: PulsarData) => d.name;
export const pulsarDataInterval = (d: PulsarData) => isMemoryData(d) ? d.interval : d.interval.value;
export const pulsarDataStart = (d: PulsarData) => isMemoryData(d) ? d.start : d.start.value;
export const pulsarDataAperture = (d: PulsarData) => isMemoryData(d) ? d.aperture : d.aperture.value;
export const pulsarDataHighest = (d: PulsarData): PlrReceiverIndex => isMemoryData(d) ? d.highestIndex : d.highestIndex.value;
export const pulsarChannelFrequency = (d: PulsarData, ch: PlrReceiverIndex): number | null => isMemoryData(d) ? d.frequencies[ch] : d.frequencies[ch].value;
/** File: the effective gain (stored 0 replaced by 1 at read); memory: the raw product, or null when never written. */
export const pulsarChannelGain = (d: PulsarData, ch: PlrReceiverIndex): number | null => isMemoryData(d) ? d.gains[ch] : d.gains[ch].effective;
/** Panel label text: the file lexeme as written, or WEB fixed2 of a memory frequency (no lexeme exists); null when unknown. */
export function pulsarFrequencyText(d: PulsarData, ch: PlrReceiverIndex): string | null {
  if (!isMemoryData(d)) return d.frequencies[ch].lexeme;
  const f = d.frequencies[ch];
  return f === null ? null : formatFixed(f, 2);
}
/** Text of the Record row's file field: the browser file name for a read file (+0x96 = 1); null when +0x96 is 0 (no suffix, 0x570e85). */
export const pulsarDataFileName = (d: PulsarData): string | null => isMemoryData(d) ? null : d.fileName;
/** Sample of channel c at row i, or null out of range (list item 0x492688). */
export function pulsarDataSample(d: PulsarData, row: number, ch: PlrReceiverIndex): number | null {
  return Number.isInteger(row) && row >= 0 && row < d.rowCount ? d.samples[row * 3 + ch] : null;
}

/**
 * What the analysis window may present (WEB-REC-NODATA). 'empty': no rows (the recovered "No Current Data to Analyze"
 * box, 0x56adfb..0x56ae20). 'reserved-name': the name equals ShortString 0x56b9bc 'No Data', whose 0x56b7d0 interval
 * overwrite and uncaptured draw branch 0x56bf11 are not ported, so it is refused rather than reinterpreted.
 */
export type PulsarDataPresentation = 'ok' | 'empty' | 'reserved-name';
export function pulsarDataPresentation(d: PulsarCurrentValue | null): PulsarDataPresentation {
  if (d === null || isClearedData(d) || d.rowCount === 0) return 'empty';
  return d.name === PLR_RESERVED_NAME ? 'reserved-name' : 'ok';
}

/**
 * THdrDisp.FormActivate 0x571748 text. A file keeps plrProperties unchanged; memory data shows the 0x5719a4 literal (+0x97 = 0)
 * or, R-RX15, the browser basename of a verified copy (+0x9a shown when +0x97 is set, 0x571931..0x57194b). `written` must be
 * the result of pulsarWrittenCopy(doc); a receipt of another data object is ignored, so older held data never shows it.
 */
export function pulsarDataProperties(d: PulsarData, written: PulsarWrittenCopy | null = null): PlrProperties {
  if (!isMemoryData(d)) return plrProperties(d);
  const h = d.highestIndex, cell = (v: number | null, digits: number) => v === null ? '' : formatFixed(v, digits);
  const file = written !== null && WRITTEN_RECEIPTS.has(written) && written.data === d ? written.fileName : PULSAR_DATA_NOT_WRITTEN;
  return Object.freeze({
    fields: Object.freeze({
      object: d.name, start: formatFixed(d.start, 8), aperture: String(d.aperture),
      // fmul Single 1000 (0x571998) then ffFixed 2
      interval: formatFixed(d.interval * 1000, 2), points: String(d.rowCount), file,
    }),
    receivers: Object.freeze(([0, 1, 2] as const).map(i => Object.freeze({
      receiver: i, recorded: i <= h, frequency: i <= h ? cell(d.frequencies[i], 2) : '', gain: i <= h ? cell(d.gains[i], 3) : '', gainZeroReplaced: false,
    }))),
  });
}

// ---------------------------------------------------------------- memory capture
export type PulsarCaptureInput = Readonly<{
  captureId: number; name: string; aperture: number; highestIndex: PlrReceiverIndex;
  frequencies: Cells<number | null>; gains: Cells<number | null>; start: number; interval: number;
  /** Flat row-major triples in append order. */
  rows: readonly number[]; full: boolean;
}>;
/** One copy of the capture rows into a Float64Array; the values are the receiver's binary64 numbers unchanged. */
export function pulsarMemoryRecording(c: PulsarCaptureInput): PulsarMemoryRecording {
  if (c.rows.length % 3 !== 0) throw new Error('capture rows are not triples');
  return Object.freeze({
    origin: 'memory', source: 'radio-receiver-model', captureId: c.captureId, name: c.name, aperture: c.aperture, highestIndex: c.highestIndex,
    frequencies: Object.freeze([...c.frequencies] as [number | null, number | null, number | null]), gains: Object.freeze([...c.gains] as [number | null, number | null, number | null]),
    start: c.start, interval: c.interval, rowCount: c.rows.length / 3, samples: Float64Array.from(c.rows), full: c.full,
  });
}

// ---------------------------------------------------------------- transitions
/**
 * Every dataset change (import, arming erase, capture commit) drops a verified-copy receipt (R-RX15); nothing revives it.
 * The spread keeps the R-RX16 output claim: an attempt in flight still owns it until its own cleanup releases it.
 */
const bump = (doc: PulsarCurrentData, data: PulsarCurrentValue | null, lease = doc.lease): PulsarCurrentData =>
  ({ ...doc, generation: doc.generation + 1, data, lease, written: null });

/**
 * Analysis Load commit. expectedGeneration is the generation when the read started: a later dataset change refuses it
 * ('superseded'); a held capture lease refuses it ('capture-lease'). A refusal changes nothing.
 */
export function importPulsarRecording(doc: PulsarCurrentData, recording: PlrRecording, expectedGeneration: number): PulsarDataStep {
  if (doc.lease) return refuse(doc, 'capture-lease');
  if (doc.generation !== expectedGeneration) return refuse(doc, 'superseded');
  return ok(bump(doc, recording));
}

/**
 * Arming (RC-REC-03). erase: the confirmed "Erasing Data" OK, which runs the clear 0x56a8e0 on a non-empty list: the rows
 * go, +0x96/+0x97/+0x98 become 0, the header cells stay. The generation must still be the one the prompt was shown for and
 * the analysis must be idle; otherwise nothing is erased and no lease is taken.
 */
export function acquirePulsarCaptureLease(doc: PulsarCurrentData, id: number, expectedGeneration: number, erase: boolean): PulsarDataStep {
  if (doc.lease) return refuse(doc, 'capture-lease');
  if (doc.analysis.modal || doc.analysis.reading) return refuse(doc, 'analysis-busy');
  if (doc.generation !== expectedGeneration) return refuse(doc, 'superseded');
  const lease = Object.freeze({ id, phase: 'armed' as const });
  if (erase && pulsarDataRows(doc.data) > 0) return ok(bump(doc, Object.freeze({ origin: 'cleared' as const, header: pulsarHeaderCells(doc.data) }), lease));
  return ok({ ...doc, lease });
}
/** Moves a held lease between 'armed', 'receiving' and 'finishing'; a committed lease only ends by its release. */
export function setPulsarCapturePhase(doc: PulsarCurrentData, id: number, phase: Exclude<PulsarCaptureLease['phase'], 'committed'>): PulsarDataStep {
  if (doc.lease?.id !== id || doc.lease.phase === 'committed') return refuse(doc, 'lease-mismatch');
  if (doc.lease.phase === phase) return Object.freeze({ doc, ok: true });
  return ok({ ...doc, lease: Object.freeze({ id, phase }) });
}
/**
 * The capture becomes the current dataset once, from a receiving or finishing lease. The lease stays held as 'committed'
 * until its release, so no import replaces the capture while its Properties and Save question are open. A second commit,
 * an armed-phase commit or another id is refused and changes nothing.
 */
export function commitPulsarCapture(doc: PulsarCurrentData, id: number, memory: PulsarMemoryRecording): PulsarDataStep {
  if (doc.lease?.id !== id || (doc.lease.phase !== 'receiving' && doc.lease.phase !== 'finishing')) return refuse(doc, 'lease-mismatch');
  return ok(bump(doc, memory, Object.freeze({ id, phase: 'committed' as const })));
}
export function releasePulsarCaptureLease(doc: PulsarCurrentData, id: number): PulsarDataStep {
  if (doc.lease?.id !== id) return refuse(doc, 'lease-mismatch');
  return ok({ ...doc, lease: null });
}
export function setPulsarAnalysisActivity(doc: PulsarCurrentData, activity: PulsarAnalysisActivity): PulsarDataStep {
  if (doc.analysis.modal === activity.modal && doc.analysis.reading === activity.reading) return Object.freeze({ doc, ok: true });
  return ok({ ...doc, analysis: Object.freeze({ modal: activity.modal, reading: activity.reading }) });
}

// ---------------------------------------------------------------- R-RX16 shared output claim
/*
 * docs/RADIO-RECORD-SAVE.md WEB-RX16-05 [W]. One browser output attempt at a time across Pulsar Analysis (R-RX15 Save) and the
 * Radio arming Save (R-RX16): each owner takes the claim with its own attempt token before its synchronous picker call and
 * releases exactly that (owner, token) once its stream cleanup settled. A newer attempt is never released by an older one.
 * Not a native flag: the original writer runs inside a modal dialog and has no such state.
 */
export type PulsarOutputOwner = 'analysis' | 'radio';
export type PulsarOutputClaim = Readonly<{ owner: PulsarOutputOwner; token: number }>;
/** 'output-busy': a claim is held (any owner). 'output-mismatch': not the held (owner, token). 'output-input': bad owner or token. */
export type PulsarOutputRefusal = 'output-busy' | 'output-mismatch' | 'output-input';
export type PulsarOutputStep = Readonly<{ doc: PulsarCurrentData; ok: true } | { doc: PulsarCurrentData; ok: false; reason: PulsarOutputRefusal }>;
/** The held output claim, or null (a document without the optional field has none). */
export const pulsarOutputClaim = (doc: PulsarCurrentData): PulsarOutputClaim | null => doc.output ?? null;
const outputInputOk = (owner: unknown, token: unknown) => (owner === 'analysis' || owner === 'radio') && Number.isSafeInteger(token) && (token as number) > 0;
/** Takes the claim for (owner, token); refused while any claim is held. Nothing else in the document changes. */
export function claimPulsarOutput(doc: PulsarCurrentData, owner: PulsarOutputOwner, token: number): PulsarOutputStep {
  if (!outputInputOk(owner, token)) return Object.freeze({ doc, ok: false, reason: 'output-input' });
  if (pulsarOutputClaim(doc) !== null) return Object.freeze({ doc, ok: false, reason: 'output-busy' });
  return Object.freeze({ doc: Object.freeze({ ...doc, output: Object.freeze({ owner, token }) }), ok: true });
}
/** Releases the claim only when it is exactly (owner, token); otherwise refused and nothing changes. */
export function releasePulsarOutput(doc: PulsarCurrentData, owner: PulsarOutputOwner, token: number): PulsarOutputStep {
  const held = pulsarOutputClaim(doc);
  if (held === null || held.owner !== owner || held.token !== token) return Object.freeze({ doc, ok: false, reason: 'output-mismatch' });
  return Object.freeze({ doc: Object.freeze({ ...doc, output: null }), ok: true });
}

// ---------------------------------------------------------------- R-RX15 verified written copy
/*
 * docs/PULSAR-SAVE-VERIFIED.md. [S] SAVE-WRITTEN (signal-write.asm 0x56a838..0x56a868): the writer closes the file, runs the I/O
 * check and only then sets +0x97 and the file name +0x9a; [S] SAVE-ORIGIN-INDEPENDENT: it never stores +0x96, so a written
 * memory capture stays memory data (no file field in a measurement row). [W] web policy: a receipt is recorded only from an
 * owned claim, after the browser stream was closed and a fresh read-back equals the claim's text byte for byte, and only
 * while the dataset is still the claimed object, generation, metadata and samples. It is historical, not a file monitor.
 *
 * Ownership: claims and receipts are frozen, hold frozen ordinary arrays (no exposed typed array) and an immutable ASCII
 * string, and are registered in module-private WeakSets. A spread copy or hand-made object is not a claim or receipt. The
 * symbol brands only shape the types; they prove no I/O.
 */
declare const CLAIM: unique symbol;
declare const WRITTEN: unique symbol;
const WRITE_CLAIMS = new WeakSet<object>(), WRITTEN_RECEIPTS = new WeakSet<object>();

/** The memory capture fields a claim owns a copy of (the object is producer-frozen; this copy is checked against it). */
export type PulsarCaptureSnapshot = Readonly<{
  captureId: number; name: string; aperture: number; highestIndex: PlrReceiverIndex;
  frequencies: Cells<number | null>; gains: Cells<number | null>; start: number; interval: number; rowCount: number; full: boolean;
}>;
export type PulsarWriteClaim = Readonly<{
  readonly [CLAIM]: true;
  data: PulsarMemoryRecording; generation: number; metadata: PulsarCaptureSnapshot;
  /** Frozen copy of the samples (Object.is comparison, so −0 and +0 differ). */
  samples: readonly number[];
  /** The canonical ASCII payload; fresh bytes are made from it for every write and compared with the read-back. */
  text: string;
}>;
export type PulsarWrittenCopy = Readonly<{
  readonly [WRITTEN]: true;
  data: PulsarMemoryRecording; generation: number; metadata: PulsarCaptureSnapshot; samples: readonly number[];
  /** The browser's basename of the chosen file (FileSystemHandle.name), never a folder path. */
  fileName: string;
  byteLength: number;
}>;
/** 'claim': not a claim this module issued. The others in check order; a refusal changes nothing (a prior receipt is kept). */
export type PulsarWriteRefusal = 'claim' | 'capture-lease' | 'superseded' | 'source-mutated' | 'readback-size' | 'readback-bytes' | 'file-name';
export type PulsarWriteStep = Readonly<{ doc: PulsarCurrentData; ok: true } | { doc: PulsarCurrentData; ok: false; reason: PulsarWriteRefusal }>;
/**
 * [S] The writer's +0x9a name copy passes ECX = 0xff (0x56a858 mov ecx,0xff) to call 0x4060cc at 0x56a85d
 * (docs/PULSAR-SAVE-VERIFIED-PROVENANCE.json, SAVE-WRITTEN copyArgument). [I] That argument is read as a bounded ShortString
 * copy; the callee is not re-inspected. [W] WEB policy, not recovered: at most 255 UTF-16 code units (no ANSI byte or
 * code-page equivalence is claimed), no C0 control or DEL and no path separator (a basename only). Refused, never cut.
 */
export const PULSAR_SAVE_NAME_MAX = 255;
export function pulsarSaveNameOk(name: unknown): name is string {
  if (typeof name !== 'string' || name.length < 1 || name.length > PULSAR_SAVE_NAME_MAX) return false;
  for (let i = 0; i < name.length; i++) { const c = name.charCodeAt(i); if (c < 0x20 || c === 0x7f || c === 0x2f || c === 0x5c) return false; }
  return true;
}

const snapshotOf = (d: PulsarMemoryRecording): PulsarCaptureSnapshot => Object.freeze({
  captureId: d.captureId, name: d.name, aperture: d.aperture, highestIndex: d.highestIndex,
  frequencies: Object.freeze([d.frequencies[0], d.frequencies[1], d.frequencies[2]] as const), gains: Object.freeze([d.gains[0], d.gains[1], d.gains[2]] as const),
  start: d.start, interval: d.interval, rowCount: d.rowCount, full: d.full,
});
const sameCells = (a: Cells<number | null>, b: Cells<number | null>) => Object.is(a[0], b[0]) && Object.is(a[1], b[1]) && Object.is(a[2], b[2]);
/** The data object still holds exactly the owned metadata and samples (Object.is per value). */
function sourceMatches(d: PulsarMemoryRecording, metadata: PulsarCaptureSnapshot, samples: readonly number[]): boolean {
  const m = metadata, s = d.samples;
  if (!(s instanceof Float64Array) || s.length !== samples.length) return false;
  if (!Object.is(d.captureId, m.captureId) || d.name !== m.name || !Object.is(d.aperture, m.aperture) || d.highestIndex !== m.highestIndex || !sameCells(d.frequencies, m.frequencies)
    || !sameCells(d.gains, m.gains) || !Object.is(d.start, m.start) || !Object.is(d.interval, m.interval) || d.rowCount !== m.rowCount || d.full !== m.full) return false;
  for (let k = 0; k < s.length; k++) if (!Object.is(s[k], samples[k])) return false;
  return true;
}
const asciiOnly = (text: string) => { for (let i = 0; i < text.length; i++) if (text.charCodeAt(i) > 0x7f) return false; return true; };

/**
 * An owned write claim for the current memory capture and its canonical payload text (the R-RX14 bytes, as built by the
 * caller in the same task). null when the data is not a producer-frozen memory capture with finite rows×3 samples, or the
 * text is empty or not ASCII. Nothing in the document changes.
 */
export function pulsarWriteClaim(doc: PulsarCurrentData, text: string): PulsarWriteClaim | null {
  const claim = claimOf(doc, text);
  if (claim) WRITE_CLAIMS.add(claim);
  return claim;
}
/** The claim object of pulsarWriteClaim, not yet registered in any claim domain. */
function claimOf(doc: PulsarCurrentData, text: string): PulsarWriteClaim | null {
  const d = doc.data;
  if (!isMemoryData(d) || !Object.isFrozen(d) || !Object.isFrozen(d.frequencies) || !Object.isFrozen(d.gains)) return null;
  if (!(d.samples instanceof Float64Array) || !Number.isInteger(d.rowCount) || d.samples.length !== d.rowCount * 3) return null;
  if (typeof text !== 'string' || text.length === 0 || !asciiOnly(text)) return null;
  const samples = Object.freeze(Array.from(d.samples));
  if (!samples.every(Number.isFinite)) return null;
  return Object.freeze({ data: d, generation: doc.generation, metadata: snapshotOf(d), samples, text }) as PulsarWriteClaim;
}
/** Fresh bytes of a claim's text, for one write. Mutating them changes neither the claim nor a later comparison. */
export function pulsarClaimBytes(claim: PulsarWriteClaim): Uint8Array<ArrayBuffer> {
  const bytes = new Uint8Array(claim.text.length);
  for (let i = 0; i < claim.text.length; i++) bytes[i] = claim.text.charCodeAt(i);
  return bytes;
}
/** Read-back against the claim's immutable text: same length, then every byte. */
export function pulsarClaimReadback(claim: PulsarWriteClaim, readback: Uint8Array): 'ok' | 'readback-size' | 'readback-bytes' {
  if (!(readback instanceof Uint8Array) || readback.length !== claim.text.length) return 'readback-size';
  for (let i = 0; i < readback.length; i++) if (readback[i] !== claim.text.charCodeAt(i)) return 'readback-bytes';
  return 'ok';
}

/**
 * Records the verified copy (the web counterpart of +0x97 := 1 and +0x9a := name after close and I/O check). Refused, in
 * order: a claim this module did not issue; a held capture lease; another data object or generation ('superseded'); the
 * same object whose metadata or samples changed in place ('source-mutated'); a read-back of another length or with any
 * different byte; a file name outside pulsarSaveNameOk. On success the data object, generation, lease and analysis activity
 * are unchanged (no adoption reset), so cursors, zoom and the measurement list stay; only `written` is set.
 */
export function recordPulsarWrittenCopy(doc: PulsarCurrentData, claim: PulsarWriteClaim, readback: Uint8Array, fileName: string): PulsarWriteStep {
  if (!WRITE_CLAIMS.has(claim)) return Object.freeze({ doc, ok: false, reason: 'claim' });
  if (doc.lease) return Object.freeze({ doc, ok: false, reason: 'capture-lease' });
  return writtenStep(doc, claim, readback, fileName);
}
/** The checks after the claim domain and the lease, in order, and the receipt. Shared by both recorders. */
function writtenStep(doc: PulsarCurrentData, claim: PulsarWriteClaim, readback: Uint8Array, fileName: string): PulsarWriteStep {
  const refuse = (reason: PulsarWriteRefusal): PulsarWriteStep => Object.freeze({ doc, ok: false, reason });
  if (doc.data !== claim.data || doc.generation !== claim.generation) return refuse('superseded');
  if (!sourceMatches(claim.data, claim.metadata, claim.samples)) return refuse('source-mutated');
  const back = pulsarClaimReadback(claim, readback);
  if (back !== 'ok') return refuse(back);
  if (!pulsarSaveNameOk(fileName)) return refuse('file-name');
  const receipt = Object.freeze({ data: claim.data, generation: claim.generation, metadata: claim.metadata, samples: claim.samples, fileName, byteLength: claim.text.length }) as PulsarWrittenCopy;
  WRITTEN_RECEIPTS.add(receipt);
  return Object.freeze({ doc: Object.freeze({ ...doc, written: receipt }), ok: true });
}

// ---------------------------------------------------------------- R-RX17 Finish-owned verified copy
/*
 * docs/RADIO-FINISH-SAVE.md WEB-RX17-02/03 [W]. The finish Save question's Yes (E4, 0x573d47..0x573d54) saves the capture while
 * the session still holds its committed lease, which recordPulsarWrittenCopy refuses (and keeps refusing). A separate claim
 * domain lets only that owner record a receipt: a finish claim is bound to the exact lease OBJECT that was current when the
 * Radio Save dialog opened (not to its numeric id, which a later lease could reuse), and to the claimed data object, generation
 * and owned metadata and samples, like a generic claim. A finish claim is never a generic claim and the reverse. The lease is
 * never released or changed here; only `written` is set.
 */
const FINISH_CLAIMS = new WeakMap<object, PulsarCaptureLease>();
/** The lease a finish claim may be issued and recorded under: the document's own committed lease, frozen, with a safe id. */
const committedLease = (doc: PulsarCurrentData, lease: PulsarCaptureLease): boolean =>
  typeof lease === 'object' && lease !== null && doc.lease === lease && Object.isFrozen(lease) && lease.phase === 'committed' && Number.isSafeInteger(lease.id);
/**
 * An owned finish claim for the current memory capture of the committed lease `lease` (the object itself), or null: another or
 * no lease (also an equal-valued copy), a phase other than committed, data that is not that capture (captureId ≠ lease id), or
 * any pulsarWriteClaim refusal. Nothing in the document changes.
 */
export function pulsarFinishWriteClaim(doc: PulsarCurrentData, lease: PulsarCaptureLease, text: string): PulsarWriteClaim | null {
  if (!committedLease(doc, lease) || !isMemoryData(doc.data) || doc.data.captureId !== lease.id) return null;
  const claim = claimOf(doc, text);
  if (claim) FINISH_CLAIMS.set(claim, lease);
  return claim;
}
/** The attempt that records: the lease object the Save dialog was opened for and the attempt's shared output token. */
export type PulsarFinishWriteOwner = Readonly<{ lease: PulsarCaptureLease; outputToken: number }>;
/**
 * Records the verified copy for the finish owner. Refused, in order: 'claim' (not a finish claim of this module, or the shared
 * output claim is not exactly ('radio', owner.outputToken)); 'capture-lease' (the claim was bound to another lease object than
 * owner.lease, or that lease is no longer the document's committed lease, or the claimed capture is not that lease's); then the
 * recordPulsarWrittenCopy tail unchanged ('superseded', 'source-mutated', 'readback-size', 'readback-bytes', 'file-name').
 * On success only `written` changes: the lease, data, generation, analysis activity and output claim stay.
 */
export function recordPulsarFinishWrittenCopy(doc: PulsarCurrentData, claim: PulsarWriteClaim, owner: PulsarFinishWriteOwner, readback: Uint8Array, fileName: string): PulsarWriteStep {
  const bound = FINISH_CLAIMS.get(claim), held = pulsarOutputClaim(doc);
  if (bound === undefined || held === null || held.owner !== 'radio' || held.token !== owner.outputToken) return Object.freeze({ doc, ok: false, reason: 'claim' });
  if (bound !== owner.lease || !committedLease(doc, bound) || claim.data.captureId !== bound.id) return Object.freeze({ doc, ok: false, reason: 'capture-lease' });
  return writtenStep(doc, claim, readback, fileName);
}
/**
 * The receipt of the current data, or null: absent, not issued here, for another object or generation, or the data's
 * metadata or samples no longer equal the owned copy.
 */
export function pulsarWrittenCopy(doc: PulsarCurrentData): PulsarWrittenCopy | null {
  const w = doc.written;
  if (!w || !WRITTEN_RECEIPTS.has(w) || w.data !== doc.data || w.generation !== doc.generation || !isMemoryData(doc.data)) return null;
  return sourceMatches(w.data, w.metadata, w.samples) ? w : null;
}
/** +0x97 of the current dataset: an imported file, or a memory capture with a valid verified copy (R-RX15). */
export const pulsarCurrentSaved = (doc: PulsarCurrentData) => isFileData(doc.data) || pulsarWrittenCopy(doc) !== null;
