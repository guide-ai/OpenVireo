/**
 * The one current pulsar signal dataset shared by the receiver Record path and the Pulsar Analysis window (R-RX4).
 * Pure TypeScript: no React, DOM, clock, RNG or storage.
 *
 * Native model (docs/RADIO-RECEIVER-RECORD.md, CLEA_VEO.exe SHA-256 781bc970…c54c): one data object behind the global
 * 0x5bcca0 (alias 0x5b5be8) holds the header at +4, the row list at +0x80, the file-origin byte +0x96, the saved byte
 * +0x97, the full byte +0x98, the new-data byte +0x99 and the file-name text +0x9a. The PLR reader 0x56a260, the Record
 * arming clear 0x56a8e0, the Receive header 0x574766..0x574969, the timer append 0x56a92c and the analysis/Properties
 * windows all use that object.
 *
 * WEB-REC-OWNER: the App owns one PulsarCurrentData document for the page lifetime (never saved, restored or sent).
 * `generation` increases on every dataset change. A receiver capture holds an exclusive lease while it is armed,
 * receiving, finishing or committed (the capture is current while the Properties and Save question are still open); while
 * it is held no import may commit (WEB-REC-TXN). The lease ends with exactly one release (Save No/Cancel, disarm, the main
 * receiver close). 'committed' is a web transaction phase, not a native flag. WEB buffered commit: the descriptor
 * changes only at the arming erase, at the capture commit (end of Identify, or the main receiver close) and at an
 * import; natively the header is written at Receive start and rows are appended to the shared object on each tick.
 *
 * A memory capture is model-generated by the receiver simulation, not observed CLEA data. It has no bytes, file name,
 * lexemes or line ending; its samples are the raw binary64 receiver signals copied once (no serialize/reparse).
 */
import { formatFixed, plrProperties, PLR_RESERVED_NAME, type PlrProperties, type PlrReceiverIndex, type PlrRecording } from './pulsarRecording';

/** Literal 0x5719a4 (AnsiString), shown by THdrDisp FileNmEd when +0x97 is 0 (0x571931..0x57194b). */
export const PULSAR_DATA_NOT_WRITTEN = 'Data Not Written to File';
/** ShortString 0x56b9bc compared with the header name at 0x56b7c9 and 0x56bf11 (same text as PLR_RESERVED_NAME). */
export const PULSAR_RESERVED_DATA_NAME = PLR_RESERVED_NAME;

type Cells<T> = readonly [T, T, T];
/**
 * Header cells at +4 as the web knows them. null: a cell no ported path has written (genuinely unrecovered or
 * uninitialized web cell). Receive writes every cell except the frequency and gain of absent receivers, which keep
 * their previous known values (WEB-REC-HEADER).
 */
export type PulsarHeaderCells = Readonly<{
  name: string | null; aperture: number | null; highestIndex: PlrReceiverIndex | null;
  frequencies: Cells<number | null>; gains: Cells<number | null>; start: number | null; interval: number | null;
}>;
export const EMPTY_PULSAR_HEADER: PulsarHeaderCells = Object.freeze({
  name: null, aperture: null, highestIndex: null, frequencies: Object.freeze([null, null, null] as const), gains: Object.freeze([null, null, null] as const), start: null, interval: null,
});

/** A finished or partial receiver capture held only in memory (+0x96 = 0, +0x97 = 0). */
export type PulsarMemoryRecording = Readonly<{
  origin: 'memory'; source: 'radio-receiver-model'; captureId: number;
  name: string; aperture: number; highestIndex: PlrReceiverIndex;
  /** Absent receivers keep the previous known cell, or null. Recorded receivers (≤ highestIndex) are always numbers. */
  frequencies: Cells<number | null>;
  /** Raw +0x53d × +0x40f products; no import zero replacement. */
  gains: Cells<number | null>;
  start: number; interval: number;
  rowCount: number;
  /** Row-major rows×3 raw binary64 receiver signals, in append order. */
  samples: Float64Array;
  /** +0x98: the append found the list at its bound. */
  full: boolean;
}>;
/** The header left after the arming clear 0x56a8e0: no rows, +0x96/+0x97/+0x98 = 0, header cells kept. */
export type PulsarClearedData = Readonly<{ origin: 'cleared'; header: PulsarHeaderCells }>;
export type PulsarData = PlrRecording | PulsarMemoryRecording;
export type PulsarCurrentValue = PulsarData | PulsarClearedData;
export const isMemoryData = (d: PulsarCurrentValue | null): d is PulsarMemoryRecording => d !== null && 'origin' in d && d.origin === 'memory';
export const isClearedData = (d: PulsarCurrentValue | null): d is PulsarClearedData => d !== null && 'origin' in d && d.origin === 'cleared';
export const isFileData = (d: PulsarCurrentValue | null): d is PlrRecording => d !== null && !('origin' in d);

export type PulsarCaptureLease = Readonly<{ id: number; phase: 'armed' | 'receiving' | 'finishing' | 'committed' }>;
/** What the analysis window reports so arming can refuse while it has a modal session or a pending read. */
export type PulsarAnalysisActivity = Readonly<{ modal: boolean; reading: boolean }>;
export type PulsarCurrentData = Readonly<{
  generation: number;
  data: PulsarCurrentValue | null;
  lease: PulsarCaptureLease | null;
  analysis: PulsarAnalysisActivity;
}>;
export const INITIAL_PULSAR_CURRENT_DATA: PulsarCurrentData = Object.freeze({
  generation: 0, data: null, lease: null, analysis: Object.freeze({ modal: false, reading: false }),
});

export type PulsarDataRefusal = 'capture-lease' | 'superseded' | 'analysis-busy' | 'lease-mismatch';
export type PulsarDataStep = Readonly<{ doc: PulsarCurrentData; ok: true } | { doc: PulsarCurrentData; ok: false; reason: PulsarDataRefusal }>;
const ok = (doc: PulsarCurrentData): PulsarDataStep => Object.freeze({ doc: Object.freeze(doc), ok: true });
const refuse = (doc: PulsarCurrentData, reason: PulsarDataRefusal): PulsarDataStep => Object.freeze({ doc, ok: false, reason });

// ---------------------------------------------------------------- accessors
/** Rows in the +0x80 list (0 for no data or a cleared header). */
export const pulsarDataRows = (d: PulsarCurrentValue | null) => d === null || isClearedData(d) ? 0 : d.rowCount;
/** +0x97: set by a successful read (0x56a49d..0x56a4be); 0 after a clear, a Receive header write and for memory data. */
export const pulsarDataSaved = (d: PulsarCurrentValue | null) => isFileData(d);
/** The header cells of the current value (the Receive seed, WEB-REC-HEADER). File gains are the effective (zero → 1) values. */
export function pulsarHeaderCells(d: PulsarCurrentValue | null): PulsarHeaderCells {
  if (d === null) return EMPTY_PULSAR_HEADER;
  if (isClearedData(d)) return d.header;
  if (isMemoryData(d)) return Object.freeze({ name: d.name, aperture: d.aperture, highestIndex: d.highestIndex, frequencies: d.frequencies, gains: d.gains, start: d.start, interval: d.interval });
  return Object.freeze({
    name: d.name, aperture: d.aperture.value, highestIndex: d.highestIndex.value,
    frequencies: Object.freeze([d.frequencies[0].value, d.frequencies[1].value, d.frequencies[2].value] as const),
    gains: Object.freeze([d.gains[0].effective, d.gains[1].effective, d.gains[2].effective] as const), start: d.start.value, interval: d.interval.value,
  });
}
export const pulsarDataName = (d: PulsarData) => d.name;
export const pulsarDataInterval = (d: PulsarData) => isMemoryData(d) ? d.interval : d.interval.value;
export const pulsarDataStart = (d: PulsarData) => isMemoryData(d) ? d.start : d.start.value;
export const pulsarDataAperture = (d: PulsarData) => isMemoryData(d) ? d.aperture : d.aperture.value;
export const pulsarDataHighest = (d: PulsarData): PlrReceiverIndex => isMemoryData(d) ? d.highestIndex : d.highestIndex.value;
export const pulsarChannelFrequency = (d: PulsarData, ch: PlrReceiverIndex): number | null => isMemoryData(d) ? d.frequencies[ch] : d.frequencies[ch].value;
/** File: the effective gain (stored 0 replaced by 1 at read); memory: the raw product, or null when never written. */
export const pulsarChannelGain = (d: PulsarData, ch: PlrReceiverIndex): number | null => isMemoryData(d) ? d.gains[ch] : d.gains[ch].effective;
/** Panel label text: the file lexeme as written, or WEB fixed2 of a memory frequency (no lexeme exists); null when unknown. */
export function pulsarFrequencyText(d: PulsarData, ch: PlrReceiverIndex): string | null {
  if (!isMemoryData(d)) return d.frequencies[ch].lexeme;
  const f = d.frequencies[ch];
  return f === null ? null : formatFixed(f, 2);
}
/** Text of the Record row's file field: the browser file name for a read file (+0x96 = 1); null when +0x96 is 0 (no suffix, 0x570e85). */
export const pulsarDataFileName = (d: PulsarData): string | null => isMemoryData(d) ? null : d.fileName;
/** Sample of channel c at row i, or null out of range (list item 0x492688). */
export function pulsarDataSample(d: PulsarData, row: number, ch: PlrReceiverIndex): number | null {
  return Number.isInteger(row) && row >= 0 && row < d.rowCount ? d.samples[row * 3 + ch] : null;
}

/**
 * What the analysis window may present (WEB-REC-NODATA). 'empty': no rows (the recovered "No Current Data to Analyze"
 * box, 0x56adfb..0x56ae20). 'reserved-name': the name equals ShortString 0x56b9bc 'No Data', whose 0x56b7d0 interval
 * overwrite and uncaptured draw branch 0x56bf11 are not ported, so it is refused rather than reinterpreted.
 */
export type PulsarDataPresentation = 'ok' | 'empty' | 'reserved-name';
export function pulsarDataPresentation(d: PulsarCurrentValue | null): PulsarDataPresentation {
  if (d === null || isClearedData(d) || d.rowCount === 0) return 'empty';
  return d.name === PLR_RESERVED_NAME ? 'reserved-name' : 'ok';
}

/** THdrDisp.FormActivate 0x571748 text. A file keeps plrProperties unchanged; memory data shows the 0x5719a4 literal (+0x97 = 0). */
export function pulsarDataProperties(d: PulsarData): PlrProperties {
  if (!isMemoryData(d)) return plrProperties(d);
  const h = d.highestIndex, cell = (v: number | null, digits: number) => v === null ? '' : formatFixed(v, digits);
  return Object.freeze({
    fields: Object.freeze({
      object: d.name, start: formatFixed(d.start, 8), aperture: String(d.aperture),
      // fmul Single 1000 (0x571998) then ffFixed 2
      interval: formatFixed(d.interval * 1000, 2), points: String(d.rowCount), file: PULSAR_DATA_NOT_WRITTEN,
    }),
    receivers: Object.freeze(([0, 1, 2] as const).map(i => Object.freeze({
      receiver: i, recorded: i <= h, frequency: i <= h ? cell(d.frequencies[i], 2) : '', gain: i <= h ? cell(d.gains[i], 3) : '', gainZeroReplaced: false,
    }))),
  });
}

// ---------------------------------------------------------------- memory capture
export type PulsarCaptureInput = Readonly<{
  captureId: number; name: string; aperture: number; highestIndex: PlrReceiverIndex;
  frequencies: Cells<number | null>; gains: Cells<number | null>; start: number; interval: number;
  /** Flat row-major triples in append order. */
  rows: readonly number[]; full: boolean;
}>;
/** One copy of the capture rows into a Float64Array; the values are the receiver's binary64 numbers unchanged. */
export function pulsarMemoryRecording(c: PulsarCaptureInput): PulsarMemoryRecording {
  if (c.rows.length % 3 !== 0) throw new Error('capture rows are not triples');
  return Object.freeze({
    origin: 'memory', source: 'radio-receiver-model', captureId: c.captureId, name: c.name, aperture: c.aperture, highestIndex: c.highestIndex,
    frequencies: Object.freeze([...c.frequencies] as [number | null, number | null, number | null]), gains: Object.freeze([...c.gains] as [number | null, number | null, number | null]),
    start: c.start, interval: c.interval, rowCount: c.rows.length / 3, samples: Float64Array.from(c.rows), full: c.full,
  });
}

// ---------------------------------------------------------------- transitions
const bump = (doc: PulsarCurrentData, data: PulsarCurrentValue | null, lease = doc.lease): PulsarCurrentData =>
  ({ ...doc, generation: doc.generation + 1, data, lease });

/**
 * Analysis Load commit. expectedGeneration is the generation when the read started: a later dataset change refuses it
 * ('superseded'); a held capture lease refuses it ('capture-lease'). A refusal changes nothing.
 */
export function importPulsarRecording(doc: PulsarCurrentData, recording: PlrRecording, expectedGeneration: number): PulsarDataStep {
  if (doc.lease) return refuse(doc, 'capture-lease');
  if (doc.generation !== expectedGeneration) return refuse(doc, 'superseded');
  return ok(bump(doc, recording));
}

/**
 * Arming (RC-REC-03). erase: the confirmed "Erasing Data" OK, which runs the clear 0x56a8e0 on a non-empty list: the rows
 * go, +0x96/+0x97/+0x98 become 0, the header cells stay. The generation must still be the one the prompt was shown for and
 * the analysis must be idle; otherwise nothing is erased and no lease is taken.
 */
export function acquirePulsarCaptureLease(doc: PulsarCurrentData, id: number, expectedGeneration: number, erase: boolean): PulsarDataStep {
  if (doc.lease) return refuse(doc, 'capture-lease');
  if (doc.analysis.modal || doc.analysis.reading) return refuse(doc, 'analysis-busy');
  if (doc.generation !== expectedGeneration) return refuse(doc, 'superseded');
  const lease = Object.freeze({ id, phase: 'armed' as const });
  if (erase && pulsarDataRows(doc.data) > 0) return ok(bump(doc, Object.freeze({ origin: 'cleared' as const, header: pulsarHeaderCells(doc.data) }), lease));
  return ok({ ...doc, lease });
}
/** Moves a held lease between 'armed', 'receiving' and 'finishing'; a committed lease only ends by its release. */
export function setPulsarCapturePhase(doc: PulsarCurrentData, id: number, phase: Exclude<PulsarCaptureLease['phase'], 'committed'>): PulsarDataStep {
  if (doc.lease?.id !== id || doc.lease.phase === 'committed') return refuse(doc, 'lease-mismatch');
  if (doc.lease.phase === phase) return Object.freeze({ doc, ok: true });
  return ok({ ...doc, lease: Object.freeze({ id, phase }) });
}
/**
 * The capture becomes the current dataset once, from a receiving or finishing lease. The lease stays held as 'committed'
 * until its release, so no import replaces the capture while its Properties and Save question are open. A second commit,
 * an armed-phase commit or another id is refused and changes nothing.
 */
export function commitPulsarCapture(doc: PulsarCurrentData, id: number, memory: PulsarMemoryRecording): PulsarDataStep {
  if (doc.lease?.id !== id || (doc.lease.phase !== 'receiving' && doc.lease.phase !== 'finishing')) return refuse(doc, 'lease-mismatch');
  return ok(bump(doc, memory, Object.freeze({ id, phase: 'committed' as const })));
}
export function releasePulsarCaptureLease(doc: PulsarCurrentData, id: number): PulsarDataStep {
  if (doc.lease?.id !== id) return refuse(doc, 'lease-mismatch');
  return ok({ ...doc, lease: null });
}
export function setPulsarAnalysisActivity(doc: PulsarCurrentData, activity: PulsarAnalysisActivity): PulsarDataStep {
  if (doc.analysis.modal === activity.modal && doc.analysis.reading === activity.reading) return Object.freeze({ doc, ok: true });
  return ok({ ...doc, analysis: Object.freeze({ modal: activity.modal, reading: activity.reading }) });
}
