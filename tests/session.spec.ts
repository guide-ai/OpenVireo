import { test,expect } from '@playwright/test';
import { createHash } from 'node:crypto';
import type { Download } from '@playwright/test';
async function bytes(download:Download):Promise<Buffer>{const stream=await download.createReadStream(),parts:Buffer[]=[];for await(const part of stream!)parts.push(part);return Buffer.concat(parts);}
test('portable session survives a page reload and exports the exact imported bytes',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/#spectrum');
  const original=Buffer.from('\uFEFFwavelength,intensity\r\n3700,.2\r\n4000,.5\r\n4700,1\r\n');
  await page.getByLabel('Import spectrum',{exact:true}).setInputFiles({name:'session-source.csv',mimeType:'text/csv',buffer:original});
  await expect(page.getByRole('heading',{name:'File ready'})).toBeVisible();
  await page.getByLabel('Object or reference').fill('Portable validation');
  await page.getByLabel('z step per tick').fill('0.0009765625');await page.getByRole('button',{name:'Apply step',exact:true}).click();
  await page.getByRole('slider').focus();for(let i=0;i<3;i++)await page.getByRole('slider').press('ArrowRight');
  await page.getByRole('button',{name:'Coarse ×10'}).click();
  await page.getByRole('button',{name:/Record measurement/}).click();await page.getByRole('button',{name:'Save measurement',exact:true}).click();
  const z=await page.getByTestId('z-value').textContent();
  const waiting=page.waitForEvent('download');await page.getByRole('button',{name:'Save session',exact:true}).click();
  const file=await waiting;expect(file.suggestedFilename()).toBe('openclea-session.json');const saved=await bytes(file);
  await page.reload();await expect(page.getByRole('button',{name:/Record measurement/})).toBeDisabled();
  await page.getByLabel('Restore analysis session',{exact:true}).setInputFiles({name:'openclea-session.json',mimeType:'application/json',buffer:saved});
  await expect(page.getByText('Session restored. The current spectrum and measurement arithmetic were checked.',{exact:true})).toBeVisible();
  await expect(page.getByTestId('z-value')).toHaveText(z!);await expect(page.getByLabel('Object or reference')).toHaveValue('Portable validation');
  await expect(page.getByRole('button',{name:'Coarse ×10'})).toHaveAttribute('aria-pressed','true');
  await expect(page.getByRole('cell',{name:'Portable validation',exact:true})).toBeVisible();
  const sourceWaiting=page.waitForEvent('download');await page.getByRole('button',{name:'Download imported spectrum',exact:true}).click();
  const restoredBytes=await bytes(await sourceWaiting);expect(restoredBytes.equals(original)).toBe(true);
  expect(createHash('sha256').update(restoredBytes).digest('hex')).toBe(JSON.parse(saved.toString()).observation.sha256);
  await page.getByRole('button',{name:/Record measurement/}).click();await page.getByRole('button',{name:'Save measurement',exact:true}).click();
  const logWaiting=page.waitForEvent('download');await page.getByRole('button',{name:/Export CSV/}).click();
  const log=(await bytes(await logWaiting)).toString();expect(log).toContain('\r\n2,2,');expect(log.split('\r\n')).toHaveLength(4);
  await page.locator('.session-card').scrollIntoViewIfNeeded();await page.screenshot({path:'test-results/session-desktop.png',fullPage:true});
  expect(errors).toEqual([]);
});
test('invalid session keeps the analysis intact and the portable controls fit mobile',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width:390,height:844});await page.goto('/#spectrum');
  await page.getByLabel('Import spectrum',{exact:true}).setInputFiles({name:'kept.csv',mimeType:'text/csv',buffer:Buffer.from('3700,.2\n4000,.5\n4700,.9')});
  await expect(page.getByRole('heading',{name:'File ready'})).toBeVisible();
  await page.getByLabel('Object or reference').fill('Keep this analysis');
  const waiting=page.waitForEvent('download');await page.getByRole('button',{name:'Save session',exact:true}).click();const saved=JSON.parse((await bytes(await waiting)).toString());
  saved.observation.sourceText=saved.observation.sourceText.replace('.2','.3');
  await page.getByLabel('Restore analysis session',{exact:true}).setInputFiles({name:'altered.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(saved))});
  await expect(page.getByRole('alert')).toContainText('The current analysis was kept');
  await expect(page.getByLabel('Object or reference')).toHaveValue('Keep this analysis');
  await expect(page.getByRole('heading',{name:'File ready'})).toBeVisible();
  await page.getByRole('button',{name:'Restore session',exact:true}).focus();await expect(page.getByRole('button',{name:'Restore session',exact:true})).toBeFocused();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.locator('.session-card').scrollIntoViewIfNeeded();await page.screenshot({path:'test-results/session-mobile.png',fullPage:true});
  expect(errors).toEqual([]);
});
