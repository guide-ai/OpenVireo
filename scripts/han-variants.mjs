// Front ZH0 (plan analysis/front-plans/front-i18n-zh.md §1.2 #2): generates src/i18n/lint/hanVariants.ts, the table of
// Simplified-only and Traditional-only characters that the zh-Hans and zh-Hant lint profiles use for script purity.
//   node scripts/han-variants.mjs            writes the table
//   node scripts/han-variants.mjs --check    exits 1 if the committed table differs from a fresh generation
// It runs locally only (CI reads the committed table): it needs ICU's `uconv` (ICU 78.3 on the machine that generated it),
// already installed; nothing is downloaded. The character sets come from Node's WHATWG decoders: the 6,763 hanzi of GB2312
// (the Simplified standard set, GBK rows 0xB0–0xF7) and the 13,060 hanzi of Big5's standard ranges (0xA440–0xC67E and
// 0xC940–0xF9D5, Taiwan's Traditional set; the HKSCS extensions are left out).
// A pair (s, t) is kept only when ICU's Hans-Hant maps s to t and Hant-Hans maps t back to s, no other character of either set maps
// to s or t (one-to-one), s is in GB2312 and not Big5 (Traditional text never writes it) and t is in Big5 and not GB2312
// (Simplified text never writes it). ICU's transform is NOT a converter (it maps 发→發, 面→麵, 干→乾 blindly); here it only proposes
// pairs that the two character sets then confirm. The SC4 hand seed stays: its 71 pairs are added even where Big5 also lists the
// Simplified form as a rare variant (个 无 极…), and the curated exclusions are never in the table. Japanese is not checked against it.
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync} from 'node:fs';
import path from 'node:path';

const ROOT=path.resolve(import.meta.dirname,'..'),OUT=path.join(ROOT,'src/i18n/lint/hanVariants.ts');
/** SC4's hand seed (src/i18n/lint/hanVariants.ts before ZH0): Simplified then Traditional, pair by pair. */
const SEED='开開关關观觀测測镜鏡谱譜数數设設选選择擇载載图圖视視时時间間远遠动動线線频頻读讀写寫输輸键鍵删刪误誤错錯帮幫页頁单單项項显顯请請确確认認闭閉统統类類级級无無变變圆圓顶頂银銀气氣过過这這们們个個为為对對话話说說现現实實验驗习習课課学學计計质質长長极極红紅蓝藍绿綠黄黃仪儀档檔储儲览覽击擊';
/** Shared or one-to-many characters never listed, whatever the data says (a hit must always be a real mix-up). */
const EXCLUDED='发髮發后後里裡裏干乾幹面麵台臺檯颱系係繫只隻复復複历歷曆范範松鬆谷穀丑醜云雲冲衝沖当當噹表錶钟鐘鍾制製尽盡儘准準卷捲斗鬥余餘苏蘇甦致緻据據蒙矇濛懞朴樸舍捨赞讚志誌划劃回迴术術征徵佣傭借藉了瞭郁鬱吁籲叶葉团團糰尸屍升昇胡鬍鬚须須咸鹹';
const hanzi=(decoder,leads,trails)=>{const d=new TextDecoder(decoder,{fatal:true}),out=[];
 for(const [lo,hi] of leads)for(let a=lo;a<=hi;a++)for(const [tl,th] of trails)for(let b=tl;b<=th;b++){
  try{const c=d.decode(new Uint8Array([a,b]));if(/^\p{sc=Han}$/u.test(c))out.push(c);}catch{/* an unassigned code */}}
 return out;};
const GB=hanzi('gbk',[[0xB0,0xF7]],[[0xA1,0xFE]]),BIG5=hanzi('big5',[[0xA4,0xC6],[0xC9,0xF9]],[[0x40,0x7E],[0xA1,0xFE]]);
const gb=new Set(GB),big5=new Set(BIG5);
const transform=(id,chars)=>{const out=execFileSync('uconv',['-f','utf-8','-t','utf-8','-x',id],{input:chars.join('\n')+'\n',encoding:'utf8'}).split('\n');
 if(out.length<chars.length)throw new Error(`uconv ${id}: ${out.length} lines for ${chars.length} characters`);
 return new Map(chars.map((c,i)=>[c,out[i]]));};
const icu=execFileSync('uconv',['--version'],{encoding:'utf8'}).trim();
const toHant=transform('Hans-Hant',GB),toHans=transform('Hant-Hans',BIG5);
const sha=(s)=>createHash('sha256').update(s).digest('hex');
const preimage=(map)=>{const m=new Map();for(const [k,v] of map){if(k===v)continue;m.set(v,(m.get(v)??0)+1);}return m;};
const intoHant=preimage(toHant),intoHans=preimage(toHans),excluded=new Set(EXCLUDED);
const pairs=new Map();
for(const [s,t] of toHant){
 if(t===s||[...t].length!==1||excluded.has(s)||excluded.has(t))continue;
 if(!gb.has(s)||big5.has(s)||!big5.has(t)||gb.has(t))continue;
 if(toHans.get(t)!==s||intoHant.get(t)!==1||intoHans.get(s)!==1)continue;
 pairs.set(s,t);
}
const seed=new Map();for(let i=0;i<SEED.length;i+=2)seed.set(SEED[i],SEED[i+1]);
// The map must stay a bijection (src/i18n/lint/rules.test.ts): a seed pair replaces any generated pair sharing one of its characters.
for(const [s,t] of seed){
 if(excluded.has(s)||excluded.has(t))throw new Error(`seed pair ${s}${t} is excluded`);
 for(const [gs,gt] of pairs)if(gs===s||gt===t||gs===t||gt===s)pairs.delete(gs);
 pairs.set(s,t);
}
const sorted=[...pairs].sort(([a],[b])=>a.codePointAt(0)-b.codePointAt(0)),text=sorted.map(([s,t])=>s+t).join('');
const chunks=text.match(/.{1,120}/gu)??[];
const source=`// GENERATED by scripts/han-variants.mjs (Front ZH0): do not edit by hand. Regenerate with \`node scripts/han-variants.mjs\`.
/** Front SC4, generated since Front ZH0 (plan front-i18n-zh.md §1.2 #2): characters that mark a Chinese string as written in the
 * other script, for the zh-Hans and zh-Hant lint profiles' script-purity rule. Each pair is a Simplified character that standard
 * Traditional text never writes and its Traditional form, which standard Simplified text never writes: proposed by ICU's Hans-Hant
 * and Hant-Hans transforms, kept only when one-to-one and confirmed by the character sets (Simplified form in GB2312 and not Big5,
 * Traditional form in Big5 and not GB2312), plus SC4's 71 hand-seeded pairs; shared and one-to-many characters (发 后 里 干 面 台 系
 * 只 复…) are excluded by name. This is a lint table, never a converter. Japanese is not checked against it.
 * Generated with ${icu}; GB2312 hanzi ${GB.length} (SHA-256 ${sha(GB.join(''))}), Big5 hanzi ${BIG5.length} (SHA-256
 * ${sha(BIG5.join(''))}); ${sorted.length} pairs (SHA-256 ${sha(text)}). */
const PAIRS=[
${chunks.map(c=>` '${c}',`).join('\n')}
].join('');
const simplified:string[]=[],traditional:string[]=[];
for(const [i,c] of [...PAIRS].entries())(i%2?traditional:simplified).push(c);
/** Simplified-only characters (a zh-Hant string must not contain them), with their Traditional forms. */
export const SIMPLIFIED_ONLY:ReadonlyMap<string,string>=new Map(simplified.map((s,i)=>[s,traditional[i]]));
/** Traditional-only characters (a zh-Hans string must not contain them), with their Simplified forms. */
export const TRADITIONAL_ONLY:ReadonlyMap<string,string>=new Map(traditional.map((t,i)=>[t,simplified[i]]));
/** SC4's hand seed, kept in the table (src/i18n/lint/rules.test.ts checks it is a subset). */
export const SEED_PAIRS='${SEED}';
/** The characters never listed (shared or one-to-many). */
export const EXCLUDED_CHARACTERS='${[...new Set(EXCLUDED)].join('')}';
`;
if(process.argv.includes('--check')){
 const now=readFileSync(OUT,'utf8');if(now!==source){console.error('src/i18n/lint/hanVariants.ts differs from a fresh generation');process.exit(1);}
 console.log(`hanVariants.ts is current (${sorted.length} pairs)`);
}else{writeFileSync(OUT,source);console.log(`${sorted.length} pairs written to src/i18n/lint/hanVariants.ts (${icu})`);}
